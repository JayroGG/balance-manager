// Expo config plugin: adopts the UIScene lifecycle on iOS. The iOS 27 SDK makes it mandatory — an app
// without UIApplicationSceneManifest is killed at launch (SIGTRAP in
// _UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption). `ios/` is gitignored and regenerated,
// so the fix lives here: Info.plist manifest + a SceneDelegate that owns the window and starts React
// Native, and an AppDelegate that no longer creates the window itself. Remove once Expo ships this.
const fs = require('fs');
const path = require('path');
const {
  withInfoPlist,
  withDangerousMod,
  withXcodeProject,
  IOSConfig,
} = require('@expo/config-plugins');

const TAG = 'withSceneLifecycle';

const SCENE_DELEGATE = `import UIKit
import React

// @generated by ${TAG} - expo prebuild (DO NOT MODIFY)
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
      let appDelegate = UIApplication.shared.delegate as? AppDelegate,
      let factory = appDelegate.reactNativeFactory
    else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    // Cold start: hand the launching URL / user activity to React Native as classic launchOptions so
    // Linking.getInitialURL (and expo-linking's initial URL) see them.
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[.url] = url
    }
    if let activity = connectionOptions.userActivities.first {
      launchOptions[.userActivityDictionary] = [
        "UIApplicationLaunchOptionsUserActivityKey": activity,
        "UIApplicationLaunchOptionsUserActivityTypeKey": activity.activityType,
      ]
    }
    // UIKit does not call the AppDelegate open/continue hooks at scene launch, so replay them BEFORE
    // React Native starts: Expo's subscribers (expo-linking initial URL, used by expo-router) get the
    // launching link, and no JS listener exists yet, so nothing is delivered twice.
    for context in connectionOptions.urlContexts {
      _ = appDelegate.application(UIApplication.shared, open: context.url, options: [:])
    }
    for activity in connectionOptions.userActivities {
      _ = appDelegate.application(
        UIApplication.shared, continue: activity, restorationHandler: { _ in })
    }
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: launchOptions)
  }

  // Warm opens go through AppDelegate so Expo's AppDelegate subscribers (expo-linking) still see them.
  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let appDelegate = UIApplication.shared.delegate as? AppDelegate else { return }
    for context in URLContexts {
      _ = appDelegate.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    guard let appDelegate = UIApplication.shared.delegate as? AppDelegate else { return }
    _ = appDelegate.application(
      UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

const WINDOW_BLOCK = /#if os\(iOS\) \|\| os\(tvOS\)\n    window = UIWindow\(frame: UIScreen\.main\.bounds\)\n    factory\.startReactNative\(\n      withModuleName: "main",\n      in: window,\n      launchOptions: launchOptions\)\n#endif\n\n/;

function patchAppDelegate(contents) {
  if (!WINDOW_BLOCK.test(contents)) {
    if (contents.includes('SceneDelegate')) return contents;
    throw new Error(`[${TAG}] AppDelegate window block not found — template changed?`);
  }
  return contents.replace(
    WINDOW_BLOCK,
    `    // @generated ${TAG}: the window is created by SceneDelegate (UIScene lifecycle)\n\n`,
  );
}

module.exports = function withSceneLifecycle(config) {
  config = withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return cfg;
  });

  config = withDangerousMod(config, [
    'ios',
    (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, cfg.modRequest.projectName);
      fs.writeFileSync(path.join(dir, 'SceneDelegate.swift'), SCENE_DELEGATE);
      const appDelegate = path.join(dir, 'AppDelegate.swift');
      fs.writeFileSync(appDelegate, patchAppDelegate(fs.readFileSync(appDelegate, 'utf8')));
      return cfg;
    },
  ]);

  return withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const name = cfg.modRequest.projectName;
    const file = `${name}/SceneDelegate.swift`;
    if (!project.hasFile(file)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath: file,
        groupName: name,
        project,
      });
    }
    return cfg;
  });
};

module.exports.patchAppDelegate = patchAppDelegate;
